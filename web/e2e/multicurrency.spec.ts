import {test, expect} from "@playwright/test";
import {create, fromBinary, toBinary} from "@bufbuild/protobuf";
import {TenantService} from "../proto/budget/v1/tenant_pb";
import {TransactionService} from "../proto/budget/v1/transaction_pb";
import {ReportService} from "../proto/budget/v1/report_pb";
import {CategoryService} from "../proto/budget/v1/category_pb";
import {AssetService} from "../proto/budget/v1/asset_pb";
import {InvestmentImportService} from "../proto/budget/v1/investment_import_pb";
import {InvestmentService} from "../proto/budget/v1/investment_pb";
import {InvestmentNAVService} from "../proto/budget/v1/investment_nav_pb";

for (const locale of ["en", "ru"]) test(`shared display currency ${locale}`, async ({page, context}, info) => {
  const services = [TenantService, TransactionService, ReportService, CategoryService, AssetService, InvestmentService, InvestmentNAVService, InvestmentImportService];
  const seen: {method:string;currency:string}[] = [];
  const errors: string[] = [];
  let writes = 0;
  page.on("pageerror", e => errors.push(e.message));
  await context.addCookies([{name:"NEXT_LOCALE",value:locale,url:info.project.use.baseURL!}]);
  await page.addInitScript(() => {
    localStorage.setItem("budget/access","currency-fixture-token");
    localStorage.setItem("budget/tenant","currency-fixture");
  });
  await page.route("**/budget.v1.*/*", async route => {
    const path = new URL(route.request().url()).pathname;
    const service = services.find(s => path.includes(s.typeName+"/"));
    const method = service?.methods.find(m => path.endsWith("/"+m.name));
    if (!method) throw new Error(`Missing fixture ${path}`);
    if (/^(Create|Update|Delete|Post)/.test(method.name)) writes++;
    const wire = route.request().postDataBuffer()!;
    const input:any = fromBinary(method.input, wire.subarray(5,5+wire.readUInt32BE(1)));
    const currency = input.targetCurrencyCode || input.currency || "RUB";
    seen.push({method:method.name,currency});
    const expense = {currencyCode:currency,minorUnits:currency==="EUR"?2000n:currency==="USD"?2500n:250000n};
    const zero = {currencyCode:currency,minorUnits:0n};
    let data:any = {};
    if (method.name==="ListMyTenants") data={memberships:[{tenant:{id:"currency-fixture",name:"Spain fixture",defaultCurrencyCode:"RUB"},role:1}]};
    if (method.name==="ListInvestmentLedgers") data={ledgers:[{id:"ledger",name:"Spain broker",portfolioTracking:true,version:1n}]};
    if (method.name==="GetInvestmentSnapshot") data={snapshot:{ledger:{id:"ledger",name:"Spain broker",portfolioTracking:true,version:1n}}};
    if (method.name==="ListInvestmentValuationProfiles") data={fxProfiles:[{key:"market",mode:"market",version:1n}]};
    if (method.name==="GetInvestmentExchangeRates") data={currency:input.currency,fxPolicyKey:"market",policyVersion:1n,mode:"market"};
    if (method.name==="ListTransactions") data={transactions:[{id:"euro-expense",type:2,categoryId:"food",comment:"Euro lunch",occurredAt:{seconds:1791417600n},amount:{currencyCode:"EUR",minorUnits:2000n},displayAmount:expense}],page:{page:1,pageSize:20,totalItems:1n,totalPages:1}};
    if (method.name==="GetTransactionsTotals") data={totalIncome:zero,totalExpense:expense};
    if (method.name==="GetMonthlySummary") data={totalIncome:zero,totalExpense:expense,items:[{categoryId:"food",categoryName:"Food",type:2,total:expense}]};
    if (method.name==="GetSummaryReport") data={totalIncome:zero,totalExpense:expense,months:["2026-10"],categories:[{categoryId:"food",categoryName:"Food",type:2,total:expense,monthlyTotals:[expense]}]};
    if (method.name==="GetDateRange") data={earliestDate:"2026-10-01",latestDate:"2026-10-31"};
    if (method.name==="GetOverview") data={total:expense,accounts:[{id:"cash",name:"Euro cash",kind:"cash",balances:[{amount:{currencyCode:"EUR",minorUnits:2000n}}]}],rates:[{fromCurrencyCode:"EUR",toCurrencyCode:currency,rateDecimal:currency==="EUR"?"1":currency==="USD"?"1.25":"125",provider:"cbr"}]};
    const body=Buffer.from(toBinary(method.output,create(method.output,data)));
    const header=Buffer.alloc(5);header.writeUInt32BE(body.length,1);
    const trailer=Buffer.from("grpc-status: 0\r\n");const end=Buffer.alloc(5);end[0]=128;end.writeUInt32BE(trailer.length,1);
    await route.fulfill({status:200,contentType:"application/grpc-web+proto",body:Buffer.concat([header,body,end,trailer])});
  });
  await page.goto("/");
  await page.setViewportSize({width:1440,height:1000});
  const stats=page.locator(".card-content").filter({has:page.locator(".text-2xl.font-bold")});
  await expect(stats).toHaveCount(3);
  for (const card of await stats.all()) {
    const padding=await card.evaluate(el=>{const s=getComputedStyle(el);return [s.paddingTop,s.paddingBottom];});
    expect(padding[0]).toBe(padding[1]);
  }
  for (const width of [390,768,1024,1280,1440]) {
    await page.setViewportSize({width,height:1000});
    expect(await page.locator("header").first().evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
  }
  await page.setViewportSize({width:1440,height:1000});
  await page.locator("header summary").filter({hasText:locale==="ru"?"Бюджет":"Budget"}).click();
  await expect(page.getByRole("link",{name:locale==="ru"?"Отчеты":"Reports",exact:true}).first()).toBeVisible();
  await page.keyboard.press("Escape");
  await page.screenshot({path:info.outputPath(`home-${locale}.png`),fullPage:true});
  const selector=page.getByRole("combobox",{name:locale==="ru"?"Валюта отображения":"Display currency"});
  await selector.selectOption("EUR");
  await expect.poll(()=>seen.some(q=>q.method==="GetMonthlySummary"&&q.currency==="EUR")).toBe(true);
  await expect(page.getByText("Euro lunch")).toBeVisible();
  await page.goto("/transactions");
  await expect(selector).toHaveValue("EUR");
  await expect.poll(()=>seen.some(q=>q.method==="GetTransactionsTotals"&&q.currency==="EUR")).toBe(true);
  await expect(page.getByText("Euro lunch")).toBeVisible();
  await page.goto("/reports");
  await expect(selector).toHaveValue("EUR");
  await expect.poll(()=>seen.filter(q=>["GetMonthlySummary","GetSummaryReport"].includes(q.method)&&q.currency==="EUR").length).toBeGreaterThan(1);
  await selector.selectOption("USD");
  await expect.poll(()=>seen.some(q=>["GetMonthlySummary","GetSummaryReport"].includes(q.method)&&q.currency==="USD")).toBe(true);
  await page.screenshot({path:info.outputPath(`reports-${locale}.png`),fullPage:true});
  await page.goto("/assets");
  await expect(selector).toHaveValue("USD");
  await expect(page.getByText("Euro cash")).toBeVisible();
  await expect.poll(()=>seen.some(q=>q.method==="GetOverview"&&q.currency==="USD")).toBe(true);
  await page.reload();await expect(selector).toHaveValue("USD");
  await page.screenshot({path:info.outputPath(`assets-${locale}.png`),fullPage:true});
  await page.goto("/investments");
  await expect(selector).toHaveValue("USD");
  await expect.poll(()=>seen.some(q=>q.method==="GetInvestmentExchangeRates"&&q.currency==="USD")).toBe(true);
  await expect(page.getByRole("navigation",{name:locale==="ru"?"Навигация инвестиций":"Investment navigation"})).toHaveCount(0);
  await page.locator("header summary").filter({hasText:locale==="ru"?"Инвестиции":"Investments"}).click();
  const investmentMenu=page.locator("header details[open]");
  await expect(investmentMenu.getByRole("link")).toHaveCount(9);
  await page.screenshot({path:info.outputPath(`investment-menu-${locale}.png`)});
  await investmentMenu.getByRole("link",{name:locale==="ru"?"Сделки":"Trades",exact:true}).click();
  await expect(page).toHaveURL(/view=trades/);
  await page.locator("header summary").filter({hasText:locale==="ru"?"Инвестиции":"Investments"}).click();
  await expect(investmentMenu.getByRole("link",{name:locale==="ru"?"Сделки":"Trades",exact:true})).toHaveAttribute("aria-current","page");
  await expect(investmentMenu.getByRole("link",{name:locale==="ru"?"Портфель":"Portfolio",exact:true})).not.toHaveAttribute("aria-current","page");
  await investmentMenu.getByRole("link",{name:locale==="ru"?"Портфель":"Portfolio",exact:true}).click();
  await page.screenshot({path:info.outputPath(`investments-${locale}.png`),fullPage:true});
  await page.getByRole("button",{name:locale==="ru"?"Переключить тему":"Toggle theme"}).click();
  await page.screenshot({path:info.outputPath(`investments-${locale}-theme.png`),fullPage:true});
  await page.goto("/investments/calendar");
  await expect.poll(()=>seen.some(q=>q.method==="GetInvestmentForecast"&&q.currency==="USD")).toBe(true);
  await expect.poll(()=>seen.some(q=>q.method==="GetInvestmentPayouts"&&q.currency==="USD")).toBe(true);
  await page.setViewportSize({width:390,height:844});
  await expect(selector).toBeVisible();
  expect(await page.locator("header").first().evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
  await page.screenshot({path:info.outputPath(`currency-${locale}-mobile.png`)});
  await page.getByRole("button",{name:locale==="ru"?"Основная навигация":"Main navigation"}).click();
  await expect(page.getByRole("heading",{name:locale==="ru"?"Бюджет":"Budget",exact:true})).toBeVisible();
  await page.getByRole("link",{name:locale==="ru"?"Главная":"Home",exact:true}).click();
  for (const route of ["/", "/reports", "/assets", "/investments", "/investments/analytics"]) {
    await page.goto(route);
    await expect(selector).toBeVisible();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
    await page.screenshot({path:info.outputPath(`mobile-${locale}-${route.replaceAll("/","_")||"home"}.png`),fullPage:true});
  }
  expect(writes).toBe(0);
  expect(errors).toEqual([]);
});
